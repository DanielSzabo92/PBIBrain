const PLACEHOLDER = /\{([a-z_]+)\}/g;

// The text for a key, with each {placeholder} replaced. A missing key gives the key itself.
export function t(key, params = {}) {
  const text = COPY[key];
  if (text === undefined) return key;
  return text.replace(PLACEHOLDER, (match, name) => (params[name] === undefined || params[name] === null ? match : String(params[name])));
}

// The count text for a key: "<key>.one" for 1, "<key>.zero" for 0 when it exists, else "<key>.other".
export function tn(key, n, params = {}) {
  const values = { n, ...params };
  if (n === 0 && COPY[`${key}.zero`] !== undefined) return t(`${key}.zero`, values);
  if (n === 1 && COPY[`${key}.one`] !== undefined) return t(`${key}.one`, values);
  return t(`${key}.other`, values);
}

// The copy key of an error code. Codes with no key use error.unknown.
export function errorKey(code) {
  if (COPY[`error.${code}`] !== undefined) return `error.${code}`;
  if (COPY[`error.${code}.body`] !== undefined) return `error.${code}.body`;
  return "error.unknown.body";
}

// The title and the text for a DevCenterError.
export function errorCopy(error) {
  const code = error?.code ?? "unknown";
  const message = error?.message ?? "";
  if (code === "action_not_allowed" && error?.details?.existing_rule_id) {
    return { title: null, body: t("error.action_not_allowed.existing_rule", { rule: error.details.existing_rule_id }) };
  }
  if (code === "action_not_allowed" && error?.details?.reason === "session_locked") {
    return { title: null, body: t("error.action_not_allowed.session_locked") };
  }
  if (code === "network") return { title: t("error.network.title"), body: t("error.network.body") };
  const key = errorKey(code);
  if (key === "error.unknown.body") return { title: t("error.unknown.title"), body: t(key, { message }).trim() };
  return { title: null, body: t(key, { message, kind: error?.details?.kind ?? "object", rule: error?.details?.rule ?? "" }) };
}

// The progress line of a long call, for example "Checking sources. Changes wait until this ends."
export function longCallText(method) {
  const key = `work.long.${method}`;
  return COPY[key] === undefined ? null : t("shared.long_call", { action: COPY[key] });
}
